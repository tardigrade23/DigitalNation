// Translation tooling for Digital Nation.
//
//   node tools/i18n.mjs extract   Collect every English string into i18n/en.json
//                                 (needs Playwright for the index.html part).
//   node tools/i18n.mjs build     Turn i18n/<code>.json into lang/<code>.js for the game.
//   node tools/i18n.mjs check     Report missing translations and broken {placeholders}.
//
// i18n/<code>.json maps English text to the translation. English is the key, so
// strings that change in the code simply show up as missing until translated.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rd = f => fs.readFileSync(path.join(root, f), 'utf8');
const SRC = path.join(root, 'i18n', 'en.json');

function fromGame() {
  const src = rd('game.js');
  const out = [];
  // t('...') and t("...") calls whose first argument is a plain string literal.
  const re = /\bt\(\s*('(?:[^'\\\n]|\\.)*'|"(?:[^"\\\n]|\\.)*")/g;
  let m;
  while ((m = re.exec(src))) out.push(vm.runInNewContext(m[1]));
  return out;
}

function fromContent() {
  const ctx = { I18N: { lang: 'en' }, t: s => s };
  vm.runInNewContext(rd('content.js') + '\n;this.LIBRARY = LIBRARY; this.NATIONAL_EVENTS = NATIONAL_EVENTS;', ctx);
  const out = [];
  for (const e of Object.values(ctx.LIBRARY)) { for (const k of ['what', 'real', 'fact', 'q']) if (e[k]) out.push(e[k]); out.push(...e.a); }
  for (const ev of ctx.NATIONAL_EVENTS) { out.push(ev.title, ev.situation, ev.real); for (const c of ev.choices) out.push(c.label); }
  return out;
}

async function fromHtml() {
  const require = createRequire(import.meta.url);
  let chromium;
  try { ({ chromium } = require('playwright')); } catch (e) { ({ chromium } = require(path.join(process.env.NODE_PATH || '', 'playwright'))); }
  const html = rd('index.html').replace(/<script\b[^>]*>[\s\S]*?<\/script>/g, '');
  const b = await chromium.launch();
  const p = await b.newPage();
  await p.route('**/*', r => r.abort());
  await p.setContent(html);
  await p.addScriptTag({ content: rd('i18n.js').replace("const lang = pick();", "const lang = 'en';") });
  const units = await p.evaluate(() => I18N.units(document.documentElement).map(u => ({ text: u.text, attr: u.attr || '', owner: u.owner ? u.owner.id : '' })));
  await b.close();
  // Skip placeholder text that game.js replaces at start (it translates its own strings).
  const game = rd('game.js');
  const dynamic = id => id && new RegExp(`\\$\\('${id}'\\)\\.(textContent|innerHTML)\\s*=`).test(game);
  return units.filter(u => u.attr || !dynamic(u.owner)).map(u => u.text);
}

async function extract() {
  const all = [...fromGame(), ...(await fromHtml()), ...fromContent()];
  const seen = new Set(), list = [];
  for (const s of all) if (s && /[A-Za-z]/.test(s) && !seen.has(s)) { seen.add(s); list.push(s); }
  fs.mkdirSync(path.dirname(SRC), { recursive: true });
  fs.writeFileSync(SRC, JSON.stringify(list, null, 1) + '\n');
  const words = list.join(' ').split(/\s+/).length;
  console.log(`i18n/en.json: ${list.length} strings, ${words} words`);
}

const holders = s => (s.match(/\{\w+\}/g) || []).sort().join(',');
const tags = s => (s.match(/<\/?[a-z]+/g) || []).sort().join(',');

function langs() {
  return fs.readdirSync(path.join(root, 'i18n')).filter(f => f.endsWith('.json') && f !== 'en.json').map(f => f.slice(0, -5));
}

function check() {
  const src = JSON.parse(fs.readFileSync(SRC, 'utf8'));
  let bad = 0;
  for (const code of langs()) {
    const d = JSON.parse(rd(`i18n/${code}.json`));
    const missing = src.filter(s => !d[s]);
    const broken = src.filter(s => d[s] && (holders(s) !== holders(d[s]) || tags(s) !== tags(d[s])));
    const stale = Object.keys(d).filter(k => !src.includes(k));
    console.log(`${code}: ${src.length - missing.length}/${src.length} translated, ${broken.length} broken, ${stale.length} unused`);
    for (const s of broken.slice(0, 10)) console.log(`   broken: ${s.slice(0, 70)} => ${d[s].slice(0, 70)}`);
    for (const s of missing.slice(0, 5)) console.log(`   missing: ${s.slice(0, 90)}`);
    bad += missing.length + broken.length;
  }
  return bad;
}

function build() {
  const src = JSON.parse(fs.readFileSync(SRC, 'utf8'));
  fs.mkdirSync(path.join(root, 'lang'), { recursive: true });
  for (const code of langs()) {
    const d = JSON.parse(rd(`i18n/${code}.json`));
    const out = {};
    for (const s of src) if (d[s] && holders(s) === holders(d[s])) out[s] = d[s];
    fs.writeFileSync(path.join(root, 'lang', `${code}.js`),
      `// Generated by tools/i18n.mjs from i18n/${code}.json. Do not edit by hand.\nI18N.add(${JSON.stringify(code)}, ${JSON.stringify(out, null, 0)});\n`);
    console.log(`lang/${code}.js: ${Object.keys(out).length} strings`);
  }
}

const cmd = process.argv[2];
if (cmd === 'extract') await extract();
else if (cmd === 'build') build();
else if (cmd === 'check') process.exitCode = check() ? 1 : 0;
else console.log('usage: node tools/i18n.mjs extract|build|check');
